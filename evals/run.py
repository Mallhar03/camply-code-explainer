import json
import statistics
from pathlib import Path

from app.agent.agent import run


def main() -> None:
    rows = [
        json.loads(line)
        for line in (Path(__file__).parent / "golden.jsonl").read_text().splitlines()
        if line.strip()
    ]
    hits = 0
    valid = 0
    refusals_correct = 0
    latencies = []
    tokens_in = []
    tokens_out = []

    for row in rows:
        result = run(row["question"])
        seed_paths = [chunk["path"] for chunk in result.trace.get("seed", [])[:5]]
        if not row["expected_files"]:
            hits += 0
        elif any(expected in seed_paths for expected in row["expected_files"]):
            hits += 1
        if result.status == "insufficient_evidence" and row["expected_status"] == "insufficient_evidence":
            refusals_correct += 1
        invalid = len(result.trace.get("invalid_citations", []))
        citations = len(result.citations)
        if citations + invalid:
            valid += citations / (citations + invalid)
        latencies.append(result.trace.get("latency_ms", 0))
        tokens_in.append(result.trace.get("tokens_in", 0))
        tokens_out.append(result.trace.get("tokens_out", 0))

    answer_rows = sum(bool(row["expected_files"]) for row in rows)
    refusal_rows = sum(not bool(row["expected_files"]) for row in rows)
    report = [
        "# Evals",
        "",
        f"Questions: {len(rows)}",
        f"Hit@5: {hits / answer_rows:.3f}" if answer_rows else "Hit@5: not measured",
        f"Citation validity rate: {valid / len(rows):.3f}",
        f"Refusal accuracy: {refusals_correct / refusal_rows:.3f}" if refusal_rows else "Refusal accuracy: not measured",
        f"Median latency: {statistics.median(latencies):.0f} ms" if latencies else "Median latency: not measured",
        f"Average input tokens: {statistics.fmean(tokens_in):.1f}" if tokens_in else "Average input tokens: not measured",
        f"Average output tokens: {statistics.fmean(tokens_out):.1f}" if tokens_out else "Average output tokens: not measured",
        "",
        "## Status",
        "Generated by `python -m evals.run`; values reflect the most recent run.",
    ]
    (Path(__file__).parent / "report.md").write_text("\n".join(report) + "\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
